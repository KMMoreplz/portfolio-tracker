package com.mikhail.common.domain;

/**
 * Вид операции над портфелем.
 */
public enum TransactionType {

    /** Покупка: увеличивает количество бумаги в портфеле. */
    BUY,

    /** Продажа: уменьшает количество бумаги в портфеле. */
    SELL,

    /** Выплата дивидендов: не меняет количество бумаг, добавляет доход. */
    DIVIDEND
}
